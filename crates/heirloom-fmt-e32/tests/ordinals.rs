use heirloom_fmt_e32::{dso_exports, OrdinalTable};

#[test]
fn parse_accepts_3_line_sample() {
    let tsv = "# header\ndll1\t1\tname1\ndll2\t2\tname2\n";
    let table = OrdinalTable::parse(tsv).expect("parse ok");
    assert_eq!(table.name_of("dll1", 1), Some("name1"));
    assert_eq!(table.name_of("DLL2", 2), Some("name2")); // case-insensitive
}

#[test]
fn parse_rejects_bad_line() {
    let tsv = "dll1\t1\n"; // only 2 fields
    let err = OrdinalTable::parse(tsv).unwrap_err();
    assert_eq!(err.0, 1);
    assert_eq!(err.1, "expected 3 fields");
}

#[test]
fn dso_exports_euser() {
    let sdk = match std::env::var("HEIRLOOM_S60_SDK_LIB") {
        Ok(v) => v,
        Err(_) => {
            eprintln!("SKIP: HEIRLOOM_S60_SDK_LIB not set");
            return;
        }
    };
    let path = std::path::Path::new(&sdk).join("euser.dso");
    let bytes = std::fs::read(&path).expect("read euser.dso");
    let exports = dso_exports(&bytes).expect("parse euser");
    let found = exports.iter().find(|e| e.ordinal == 1);
    assert!(found.is_some(), "ordinal 1 not found");
    let e = found.unwrap();
    assert_eq!(e.dll, "euser{000a0000}[100039e5].dll");
    assert_eq!(e.name, "_Z16PanicTFixedArrayv");
    assert!(exports.iter().all(|e| e.ordinal != 0), "no ordinal should be 0");
}

#[test]
fn hero_of_sparta_resolves() {
    let corpus = match std::env::var("HEIRLOOM_E32_CORPUS") {
        Ok(v) => v,
        Err(_) => {
            eprintln!("SKIP: HEIRLOOM_E32_CORPUS not set");
            return;
        }
    };
    // data/eka-ordinals.tsv is generated by examples/gen_eka_ordinals from the SDK (see its header) and committed.
    let tsv = include_str!("../data/eka-ordinals.tsv");
    let table = OrdinalTable::parse(tsv).expect("parse tsv");
    let path = std::path::Path::new(&corpus).join("HeroOfSparta.exe");
    let bytes = std::fs::read(&path).expect("read HeroOfSparta");
    let img = heirloom_fmt_e32::E32Image::parse(&bytes).expect("parse e32");
    let mut unnamed: Vec<(String, u16)> = Vec::new();
    for d in &img.imports {
        for imp in &d.imports {
            if table.name_of(&d.name, imp.ordinal).is_none() {
                unnamed.push((d.name.clone(), imp.ordinal));
            }
        }
    }
    // MEASURED 2026-10-26: 633 / 704 imports named from the S60 5th Edition SDK. The 71 unnamed are all Symbian^3 interfaces
    // that SDK predates (libGLESv1_CM 53, libEGL 11 - the 5th SDK has only libgles_cm - and newer exports of goommonitor 3,
    // ws32 2, BrowserLauncher 2): a SHRINK-ONLY floor until a Symbian^3 SDK's stubs are added to the generator's input.
    const UNNAMED_FLOOR: usize = 71;
    let s3 = ["libglesv1_cm{000a0000}.dll", "libegl{000a0000}.dll", "goommonitor{000a0000}[10282dbf].dll", "ws32{000a0000}[10003b21].dll", "browserlauncher{000a0000}[101f8559].dll"];
    let outside: Vec<_> = unnamed.iter().filter(|(d, _)| !s3.contains(&d.to_ascii_lowercase().as_str())).collect();
    assert!(outside.is_empty(), "imports unnamed outside the known Symbian^3 gap: {:?}", &outside[..outside.len().min(10)]);
    assert!(unnamed.len() <= UNNAMED_FLOOR, "{} unnamed (floor {UNNAMED_FLOOR}): a regression in the table or the reader", unnamed.len());
    if unnamed.len() < UNNAMED_FLOOR {
        eprintln!("NOTE: {} unnamed, below the floor {UNNAMED_FLOOR} - lower UNNAMED_FLOOR in this test", unnamed.len());
    }
}