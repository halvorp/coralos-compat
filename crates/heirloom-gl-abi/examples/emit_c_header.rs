//! Prints `rgl_entries.h`: the C numbering of the contract table, for the worker (`userland/coral-heirloom-gl`).
//! `cargo run -q --example emit_c_header > rgl_entries.h`; the worker's copy must equal this output byte for byte.
use heirloom_gl_abi::contract::{entries_digest, ENTRIES};

fn main() {
    println!("/* GENERATED by heirloom-gl-abi `cargo run --example emit_c_header`: the contract table's numbering. Do not edit. */");
    println!("#ifndef RGL_ENTRIES_H\n#define RGL_ENTRIES_H");
    println!("#define RGL_ENTRIES_COUNT {}", ENTRIES.len());
    println!("#define RGL_ENTRIES_DIGEST 0x{:016x}ull", entries_digest(ENTRIES));
    for (i, e) in ENTRIES.iter().enumerate() {
        println!("#define RGL_E_{} {}", e.name, i);
    }
    println!("static const char *const RGL_ENTRY_NAMES[RGL_ENTRIES_COUNT] = {{");
    for e in ENTRIES {
        println!("    \"{}\",", e.name);
    }
    println!("}};");
    println!("#endif");
}
