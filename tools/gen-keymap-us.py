#!/usr/bin/env python3
"""Generate crates/heirloom-ami68k-engine/src/keymap_us.rs from an AROS keymap descriptor (default: the US PC keymap).

    tools/gen-keymap-us.py /data/refs/heirloom/AROS/workbench/devs/keymaps/pc104_usa.akmd > crates/heirloom-ami68k-engine/src/keymap_us.rs

The descriptor (APL) is read for FACTS only (which character each raw key gives under each qualifier combination, the string
descriptors of the function keys, the caps-lock and key-repeat bits); the output is data, not AROS code. The file is Latin-1.
"""
import re, sys

path = sys.argv[1] if len(sys.argv) > 1 else "/data/refs/heirloom/AROS/workbench/devs/keymaps/pc104_usa.akmd"
text = open(path, encoding="latin-1").read()
FLAGS = {"KC_NOQUAL": 0, "KCF_SHIFT": 1, "KCF_ALT": 2, "KCF_CONTROL": 4, "KCF_DOWNUP": 8, "KCF_DEAD": 32, "KCF_STRING": 64, "KCF_NOP": 128, "KC_VANILLA": 7}

sections = {}
for m in re.finditer(r"## begin (\w+)\n(.*?)## end \1", text, re.S):
    sections.setdefault(m.group(1), []).append(m.group(2))

def lines(body):
    for l in body.splitlines():
        l = re.sub(r"\s#.*$", "", l) if "'#'" not in l else l
        l = l.split("#")[0] if "'#'" not in l else l
        if l.strip(): yield l.strip()

TOK = re.compile(r"'(\\.|[^'\\])'|0x[0-9A-Fa-f]+|\d+")
def values(line):
    out = []
    for m in TOK.finditer(line):
        t = m.group(0)
        if t.startswith("'"):
            c = m.group(1)
            c = {"\\\\": "\\", "\\'": "'", "\\n": "\n"}.get(c, c)
            out.append(ord(c))
        else: out.append(int(t, 0))
    return out

def types(name):
    return [sum(FLAGS[f.strip()] for f in l.split("|")) for l in lines(sections[name][0])]
def bits(name):
    v = [x for l in lines(sections[name][0]) for x in values(l)]
    return [sum(b << i for i, b in enumerate(v[k:k + 8])) for k in range(0, len(v), 8)]

lo_types, hi_types = types("lokeymaptypes"), types("hikeymaptypes")
strings = []
for body in sections["string"]:
    ls = list(lines(body))
    assert ls[0].startswith("id:")
    strings.append((ls[0][3:].strip(), [x for l in ls[1:] for x in values(l)]))
names = [n for n, _ in strings]
lo_map = [values(l) for l in lines(sections["lokeymap"][0])]
hi_map = []
for l in lines(sections["hikeymap"][0]):
    if l.startswith("id:"): hi_map.append(("Str", names.index(l[3:].strip())))
    else:
        v = values(l); assert len(v) == 4, l
        hi_map.append(("Bytes", (v[0] << 24) | (v[1] << 16) | (v[2] << 8) | v[3]))
assert len(lo_types) == 64 and len(lo_map) == 64 and len(hi_types) == 56 and len(hi_map) == 56, (len(lo_types), len(lo_map), len(hi_types), len(hi_map))
print("//! The default (US PC) keymap as data: GENERATED by tools/gen-keymap-us.py from AROS workbench/devs/keymaps/pc104_usa.akmd")
print("//! (APL; the key-to-character facts only). Do not edit; keymap.rs lays it out as a real `struct KeyMap` in guest memory.")
print("#![allow(clippy::all)]\n")
print(f"pub const LO_TYPES: [u8; 64] = {lo_types};")
print(f"pub const HI_TYPES: [u8; 56] = {hi_types};")
print("pub const LO_MAP: [u32; 64] = [" + ", ".join("0x%08X" % ((a << 24) | (b << 16) | (c << 8) | d) for a, b, c, d in lo_map) + "];")
print("/// A high-keymap entry: four characters, or the index of a string descriptor in [`STRINGS`].")
print("#[derive(Clone, Copy)]\npub enum Hi { Bytes(u32), Str(usize) }")
print("pub const HI_MAP: [Hi; 56] = [" + ", ".join(f"Hi::{k}(0x%08X)" % v if k == "Bytes" else f"Hi::Str({v})" for k, v in hi_map) + "];")
print(f"pub const LO_CAPS: [u8; 8] = {bits('locapsable')};")
print(f"pub const HI_CAPS: [u8; 7] = {bits('hicapsable')};")
print(f"pub const LO_REPEAT: [u8; 8] = {bits('lorepeatable')};")
print(f"pub const HI_REPEAT: [u8; 7] = {bits('hirepeatable')};")
print("/// (name, bytes) of every string descriptor: pairs of (length, offset) per qualifier combination, then the strings.")
print("pub const STRINGS: [(&str, &[u8]); %d] = [" % len(strings))
for n, d in strings: print(f'    ("{n}", &{d}),')
print("];")
