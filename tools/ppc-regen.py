#!/usr/bin/env python3
"""Regenerate the retro-ppc test oracles with LLVM's PowerPC assembler (an encoder independent of ours).

  tests/common/oracle.rs    every instruction literal (`asm("..")`, `r("..", ..)` and `&["..", ..]` lists) found in crates/retro-ppc/tests/*.rs, one line each,
                            assembled with `llvm-mc -triple=powerpc` (word table: text -> encoding)
  tests/common/programs.rs  every crates/retro-ppc/tests/asm/*.s assembled to a big-endian word array

Run after adding or changing an asm("...") literal or a .s file:  python3 tools/ppc-regen.py
The tests never invoke LLVM: they read the committed tables, so `cargo test` needs no toolchain beyond Rust.
"""
import glob, os, re, subprocess, sys, tempfile

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "retro-ppc", "tests")
MC = ["llvm-mc", "-triple=powerpc", "-mcpu=750"]

def one(line):
    out = subprocess.run(MC + ["-show-encoding"], input=line + "\n", capture_output=True, text=True)
    m = re.search(r"encoding: \[(0x[0-9a-f]{2}),(0x[0-9a-f]{2}),(0x[0-9a-f]{2}),(0x[0-9a-f]{2})\]", out.stdout)
    if not m:
        sys.exit(f"cannot assemble {line!r}: {out.stderr.strip()}")
    return int("".join(x[2:] for x in m.groups()), 16)

lits = set()
for f in glob.glob(os.path.join(root, "*.rs")) + [os.path.join(root, "common", "mod.rs")]:
    src = open(f).read()
    lits |= set(re.findall(r'\basm\("([^"]*)"\)', src))
    lits |= set(re.findall(r'\br\("([^"]*)"', src))          # local helper closures `r("insn", ...)`
    for lst in re.findall(r'&\[((?:\s*"[^"]*"\s*,?)+)\]', src):  # program lists `&["insn", "insn"]`
        lits |= set(re.findall(r'"([^"]*)"', lst))
with open(os.path.join(root, "common", "oracle.rs"), "w") as o:
    o.write("// GENERATED by tools/ppc-regen.py from llvm-mc -triple=powerpc. Do not edit.\n")
    o.write("pub const ORACLE: &[(&str, u32)] = &[\n")
    for s in sorted(lits):
        o.write(f'    ("{s}", {one(s):#010x}),\n')
    o.write("];\n")

with open(os.path.join(root, "common", "programs.rs"), "w") as o:
    o.write("// GENERATED by tools/ppc-regen.py from tests/asm/*.s (llvm-mc + llvm-objcopy). Do not edit.\n")
    for s in sorted(glob.glob(os.path.join(root, "asm", "*.s"))):
        name = os.path.basename(s)[:-2].upper()
        with tempfile.TemporaryDirectory() as t:
            obj, binf = os.path.join(t, "a.o"), os.path.join(t, "a.bin")
            subprocess.run(MC + ["-filetype=obj", s, "-o", obj], check=True)
            subprocess.run(["llvm-objcopy", "-O", "binary", "-j", ".text", obj, binf], check=True)
            data = open(binf, "rb").read()
        words = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
        o.write(f"/// Assembled from tests/asm/{os.path.basename(s)}.\npub const {name}: &[u32] = &[\n")
        for i in range(0, len(words), 6):
            o.write("    " + ", ".join(f"{w:#010x}" for w in words[i:i + 6]) + ",\n")
        o.write("];\n")
