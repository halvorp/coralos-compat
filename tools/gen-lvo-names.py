#!/usr/bin/env python3
"""Generate crates/amiga68k-engine/src/lvo_names.rs: every public function of the common AmigaOS libraries with its
LVO, from AROS's `.conf` function lists (interface facts: names and vector numbers). Usage: gen-lvo-names.py AROS_DIR.
Offsets: a list that starts with the library's own open() declares the four standard vectors (Open, Close, Expunge,
Reserved) itself; one that does not, leaves them implicit. Known anchors are asserted so a miscount cannot ship."""
import re, sys, os
AROS = sys.argv[1]
LIBS = [("exec","rom/exec"),("dos","rom/dos"),("intuition","rom/intuition"),("graphics","rom/graphics"),
        ("gadtools","workbench/libs/gadtools"),("utility","rom/utility"),("layers","rom/hyperlayers"),("keymap","rom/keymap"),
        ("mathieeedoubbas","workbench/libs/mathieeedoubbas"),("mathieeedoubtrans","workbench/libs/mathieeedoubtrans"),
        ("mathffp","workbench/libs/mathffp"),("icon","workbench/libs/icon"),("workbench","workbench/libs/workbench"),
        ("asl","workbench/libs/asl"),("diskfont","workbench/libs/diskfont"),("locale","workbench/libs/locale"),
        ("muimaster","workbench/libs/muimaster"),("commodities","workbench/libs/commodities"),
        ("rexxsyslib","workbench/libs/rexxsyslib"),("lowlevel","workbench/libs/lowlevel"),("iffparse","workbench/libs/iffparse"),
        ("datatypes","workbench/libs/datatypes"),("cybergraphics","workbench/libs/cgfx"),
        ("timer.device","rom/timer"),("input.device","rom/devs/input"),("console.device","rom/devs/console")]
ANCHORS = {("timer.device","GetSysTime"):-66,("timer.device","AddTime"):-42,("timer.device","BeginIO"):-30,
           ("input.device","PeekQualifier"):-42,("exec","Wait"):-318,("exec","OpenLibrary"):-552,("exec","CloseLibrary"):-414,("exec","FindTask"):-294,
           ("dos","Open"):-30,("intuition","OpenWindow"):-204,("intuition","CloseWindow"):-72,
           ("intuition","OpenWindowTagList"):-606,("graphics","Text"):-60,("gadtools","CreateGadgetA"):-30,
           ("mathieeedoubbas","IEEEDPFix"):-30,
           ("lowlevel","ReadJoyPort"):-30,("lowlevel","GetKey"):-48,("lowlevel","QueryKeys"):-54}
def parse(path):
    L = open(path).read().split("\n")
    s = next(i for i, l in enumerate(L) if l.strip() == "##begin functionlist")
    entries = []  # (index, name or None)
    for l in L[s + 1:]:
        l = l.split("#")[0].strip() if not l.strip().startswith("##") else l.strip()
        if l == "##end functionlist": break
        if not l: continue
        m = re.match(r"\.skip\s+(\d+)", l)
        if m: entries += [None] * int(m.group(1)); continue
        if l.startswith("."): continue
        n = re.match(r".*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", l)
        entries.append(n.group(1) if n else None)
    first = next((e for e in entries if e), "")
    explicit = first.lower() in ("open", "openlib")
    # A device declares beginio_func/abortio_func in its config block: its two device vectors (BeginIO -30,
    # AbortIO -36) follow the four standard ones implicitly, so its own list starts at -42.
    device = any(l.strip().startswith("beginio_func") for l in L[:s])
    base = 0 if explicit else (6 if device else 4)
    named = [(-30, "BeginIO"), (-36, "AbortIO")] if device else []
    return named + [(-6 * (base + i + 1), e) for i, e in enumerate(entries) if e and not (explicit and i < 4)]
out = ["// GENERATED by tools/gen-lvo-names.py from AROS's .conf function lists (interface facts: names and vector",
       "// numbers). Do not edit. Regenerate: python3 tools/gen-lvo-names.py <AROS tree>.",
       "/// (library name, [(LVO, function name)]), each list in vector order.",
       "pub static LIBRARIES: &[(&str, &[(i32, &str)])] = &["]
seen = {}
for lib, d in LIBS:
    full = lib if "." in lib else lib + ".library"
    fns = parse(os.path.join(AROS, d, full.split(".")[0] + ".conf"))
    for (l, f), want in ANCHORS.items():
        if l == lib:
            got = dict((n, o) for o, n in fns).get(f)
            assert got == want, f"{lib}/{f}: generated {got}, known {want}"
    out.append(f'    ("{full}", &[' + ", ".join(f'({o}, "{n}")' for o, n in fns) + "]),")
    seen[lib] = len(fns)
out.append("];")
dst = os.path.join(os.path.dirname(__file__), "..", "crates/amiga68k-engine/src/lvo_names.rs")
open(dst, "w").write("\n".join(out) + "\n")
print(" ".join(f"{k}={v}" for k, v in seen.items()))
