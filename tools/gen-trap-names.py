#!/usr/bin/env python3
"""Generate crates/mac68k-engine/src/trap_names.rs: every classic Mac A-line trap word with its name (interface facts:
numbers and names) from metamage_1's relix/files/etc/traps, one `XXXX<TAB>_Name` per line. Where a trap has two names
(old spelling first, e.g. _DisposWindow / _DisposeWindow) the LATER one wins. Usage: gen-trap-names.py <traps file>.
Anchors are asserted so a bad parse cannot ship."""
import re, sys
names = {}
for line in open(sys.argv[1], encoding="latin-1"):
    m = re.fullmatch(r"([0-9A-F]{4})\t_(\w+)\n?", line)
    if m: names[int(m.group(1), 16)] = m.group(2)
for k, v in {0xA913: "NewWindow", 0xA914: "DisposeWindow", 0xA970: "GetNextEvent", 0xA860: "WaitNextEvent",
             0xA9F4: "ExitToShell", 0xA86E: "InitGraf"}.items():
    assert names[k] == v, (hex(k), names.get(k))
out = ["// GENERATED by tools/gen-trap-names.py from metamage_1's relix/files/etc/traps (interface facts: trap words and",
       "// names). Do not edit. Regenerate: python3 tools/gen-trap-names.py <traps file>.",
       "/// (trap word, name without the leading underscore), ascending by trap word.",
       "pub static TRAPS: &[(u16, &str)] = &["]
out += [f'    (0x{k:04X}, "{names[k]}"),' for k in sorted(names)]
out.append("];")
open("crates/mac68k-engine/src/trap_names.rs", "w").write("\n".join(out) + "\n")
print(len(names), "traps")
