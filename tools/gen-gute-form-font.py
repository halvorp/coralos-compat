#!/usr/bin/env python3
"""Rasterise the Gute Form UI font (Nunito Sans Regular, the kit's --font-ui) into an Amiga TextFont strip.

Usage: gen-gute-form-font.py <NunitoSans-Regular.ttf> > crates/heirloom-theme/src/uifont_data.rs

The font is the CoralOS UI kit's UI face (CoralOS_UIKit.html `--font-ui:"Nunito Sans"`, strata_theme.rs text::SCALE_UI),
SIL OFL 1.1, Copyright 2016 The Nunito Sans Project Authors (https://github.com/Fonthausen/NunitoSans). FreeType's 1-bit
(mono) rasteriser draws every glyph of ISO-8859-1 (32..=255) at EM px; the strip is the classic planar layout
(graphics/text.h): MODULO bytes a row, CharLoc = bit offset << 16 | bit width, CharSpace, CharKern.
Needs Pillow with FreeType. Output is deterministic for a given Pillow/FreeType; the committed file is the artefact.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

EM = 12                 # the smallest size of the kit's UI scale (strata_theme.rs text::SCALE_UI = 12, 14, 16, 20, 24)
LO, HI = 32, 255
W, H, OX, BASE = 40, 40, 12, 28   # scratch cell: glyph origin x, baseline row

font = ImageFont.truetype(sys.argv[1], EM, layout_engine=ImageFont.Layout.BASIC)

def render(ch):
    im = Image.new("L", (W, H), 255)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((OX, BASE), ch, font=font, fill=0, anchor="ls")
    px = [[im.getpixel((x, y)) < 128 for x in range(W)] for y in range(H)]
    return px

def ink_box(px):
    xs = [x for r in px for x, v in enumerate(r) if v]
    ys = [y for y, r in enumerate(px) if any(r)]
    return (min(xs), max(xs), min(ys), max(ys)) if xs else None

# vertical metrics from plain ascenders and descenders (accents on capitals may clip: see LICENSES/NOTICE note)
asc = max(BASE - ink_box(render(c))[2] for c in "bdfhklt")
desc = max(ink_box(render(c))[3] - BASE + 1 for c in "gjpqy")
# Amiga: tf_Baseline is the row index of the baseline row; rows 0..=baseline sit on or above it, the ascenders end AT it.
baseline = asc - 1
Y = asc + desc

glyphs = []   # (rows[Y] of bit-lists, width, lsb, adv)
def box_glyph():
    w = EM // 2 + 1
    rows = [[False] * w for _ in range(Y)]
    for y in range(asc - 8 if asc >= 8 else 0, baseline + 1):
        for x in range(w):
            if y in (asc - 8 if asc >= 8 else 0, baseline) or x in (0, w - 1): rows[y][x] = True
    return rows, w, 0, w + 1

for code in range(LO, HI + 2):   # HI + 1 = the default glyph
    if code > HI or 127 <= code <= 159:
        glyphs.append(box_glyph()); continue
    ch = chr(code)
    px = render(ch)
    adv = int(font.getlength(ch) + 0.5)
    b = ink_box(px)
    if b is None:
        glyphs.append(([[False] * 0 for _ in range(Y)], 0, 0, adv)); continue
    x0, x1, _, _ = b
    rows = []
    for yy in range(Y):
        sy = BASE - asc + yy   # strip row 0 = the ascender top (scratch row BASE - asc); row `baseline` = BASE - 1, the last ink row above the baseline
        rows.append([px[sy][x] if 0 <= sy < H else False for x in range(x0, x1 + 1)])
    lsb = x0 - OX
    w = x1 - x0 + 1
    adv = max(adv, lsb + w)
    glyphs.append((rows, w, lsb, adv))
    if code < 128 and (ch.isupper() or ch in "bdfhklt"):   # plain ascenders and capitals must keep every ink row the rasteriser drew
        kept = [y for y in range(Y) if any(rows[y])]
        assert kept and kept[-1] - kept[0] == b[3] - b[2], f"{ch!r} clipped: strip ink rows {kept}, ttf ink rows {b[2]}..{b[3]}"

total = sum(g[1] for g in glyphs)
modulo = ((total + 15) // 16) * 2
data = [[0] * (modulo * 8) for _ in range(Y)]
loc, space, kern, off = [], [], [], 0
for rows, w, lsb, adv in glyphs:
    for yy in range(Y):
        for x in range(w):
            if rows[yy][x]: data[yy][off + x] = 1
    loc.append(off << 16 | w)
    kern.append(lsb)
    space.append(adv - lsb)          # cursor: += kern, draw, += space  (so the total advance is adv)
    off += w
blob = bytearray()
for yy in range(Y):
    for i in range(modulo):
        v = 0
        for k in range(8): v = v << 1 | data[yy][i * 8 + k]
        blob.append(v)
xsize = int(font.getlength("0") + 0.5)

def arr(name, ty, vals, per, fmt):
    s = f"pub const {name}: [{ty}; {len(vals)}] = [\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",\n"
    return s + "];\n"

print("// GENERATED by tools/gen-gute-form-font.py from NunitoSans-Regular.ttf (SIL OFL 1.1) -- do not edit.")
print(f"// Nunito Sans Regular rasterised 1-bit at {EM} px, ISO-8859-1 32..=255 plus the default glyph. See LICENSES.md.")
print(f"pub const EM_PX: u16 = {EM};")
print(f"pub const Y_SIZE: u16 = {Y};\npub const X_SIZE: u16 = {xsize};\npub const BASELINE: u16 = {baseline};\npub const BOLD_SMEAR: u16 = 1;")
print(f"pub const LO_CHAR: u8 = {LO};\npub const HI_CHAR: u8 = {HI};\npub const MODULO: u16 = {modulo};")
print(arr("CHAR_DATA", "u8", list(blob), 16, lambda v: f"0x{v:02x}"))
print(arr("CHAR_LOC", "u32", loc, 6, lambda v: f"0x{v:08x}"))
print(arr("CHAR_SPACE", "i16", space, 16, str))
print(arr("CHAR_KERN", "i16", kern, 16, str))
