#!/usr/bin/env python3
"""Generate crates/amiga68k-engine/src/mui/{ids_gen,names}.rs from MUI's own interface header (libraries/mui.h, the MUI 3.8 developer
kit header shipped with AROS's openurl and zune MCC includes; Zune's agrees). INTERFACE FACTS only (names and numbers); no code is copied.
  ids_gen.rs: one `pub const` per MUIA_/MUIM_/MUIV_/MUII_/MUIO_ name that the engine's mui/*.rs sources mention (so a typo is a compile error
              and the number is never hand-typed);
  names.rs  : id -> name for EVERY attribute and method of the header, so a refusal says MUIA_Text_Foo instead of 0x8042....
Usage: tools/gen-mui-ids.py [HEADER]   (default: the AROS openurl copy under /data/refs/retro)"""
import re, sys, os, glob
HDR = sys.argv[1] if len(sys.argv) > 1 else "/data/refs/retro/AROS/external/openurl/include/libraries/mui.h"
SRC = os.path.join(os.path.dirname(__file__), "..", "crates", "amiga68k-engine", "src", "mui")
text = open(HDR, "rb").read().decode("latin1")
vals = {}
for m in re.finditer(r"^#define\s+(MUI[AMVOI]_\w+)\s+(.*)$", text, re.M):
    name, rhs = m.group(1), re.sub(r"/\*.*?\*/", "", m.group(2)).strip()
    rhs = re.sub(r"\s*//.*$", "", rhs).strip()
    mm = re.fullmatch(r"\(?\s*(-?\d+|0x[0-9a-fA-F]+)\s*\)?", rhs) or re.fullmatch(r"\(?\s*\(\w+\)\s*(-?\d+|0x[0-9a-fA-F]+)\s*\)?", rhs)
    sh = re.fullmatch(r"\(?\s*\(?1\s*<<\s*(\d+)\)?\s*\)?", rhs)
    if mm: vals[name] = int(mm.group(1), 0) & 0xFFFFFFFF
    elif sh: vals[name] = 1 << int(sh.group(1))
# Names Zune added beyond MUI 3.8's header (multi-line defines in its class headers). Bases: MUIB_MUI = TAG_USER = 0x80000000,
# MUIB_RSVD = MUIB_MUI | 0x10400000, MUIB_ZUNE = MUIB_RSVD | 0x20000 (mui_identifiers.h), and per-class bases `MUIB_Class = MUIB_ZUNE | n`.
ZUNE = os.environ.get("ZUNE_CLASSES", "/data/refs/retro/AROS/workbench/libs/muimaster/classes")
bases = {"MUIB_MUI": 0x80000000, "MUIB_RSVD": 0x90400000, "MUIB_ZUNE": 0x90420000}
src = {f: open(f, "rb").read().decode("latin1") for f in glob.glob(os.path.join(ZUNE, "*.h"))}
for _ in range(3):
    for t in src.values():
        for m in re.finditer(r"#define\s+(MUIB_\w+)\s+\((MUIB_\w+)\s*\|\s*0x([0-9a-fA-F]+)\)", t):
            if m.group(2) in bases: bases[m.group(1)] = bases[m.group(2)] | int(m.group(3), 16)
for t in src.values():
    for m in re.finditer(r"#define\s+(MUI[AM]_\w+)\s*\\?\s*\((MUIB_\w+)\s*\|\s*0x([0-9a-fA-F]+)\)", t):
        if m.group(2) in bases: vals.setdefault(m.group(1), (bases[m.group(2)] | int(m.group(3), 16)) & 0xFFFFFFFF)
for t in src.values():   # enum-style MUIV_ constants in the class headers
    for m in re.finditer(r"^\s*(MUIV_\w+)\s*=\s*(-?\d+|0x[0-9a-fA-F]+)\s*,?", t, re.M):
        vals.setdefault(m.group(1), int(m.group(2), 0) & 0xFFFFFFFF)
used = set()
for f in glob.glob(os.path.join(SRC, "*.rs")) + glob.glob(os.path.join(SRC, "..", "translate", "mui.rs")):
    if os.path.basename(f) in ("ids_gen.rs", "names.rs"): continue
    used |= set(re.findall(r"\b(MUI[AMVOI]_\w+)\b", open(f).read()))
# MUIO_ types are in mui.h as plain numbers with a different prefix
for m in re.finditer(r"^#define\s+(MUIO_\w+)\s+(\d+)", text, re.M): vals.setdefault(m.group(1), int(m.group(2)))
missing = sorted(u for u in used if u not in vals)
if missing: print("not in the header (hand-defined in ids.rs?):", " ".join(missing), file=sys.stderr)
def rust(n, v):
    kind = "i32" if n.startswith(("MUII_", "MUIO_")) or v in () else "u32"
    return f"pub const {n}: u32 = {v:#010x};" if n[3] in "AM" else f"pub const {n}: u32 = {v};"
with open(os.path.join(SRC, "ids_gen.rs"), "w") as o:
    o.write("//! GENERATED by tools/gen-mui-ids.py from MUI's libraries/mui.h (interface facts: names and numbers). Do not edit.\n")
    o.write("#![allow(dead_code, non_upper_case_globals)]\n")
    for n in sorted(u for u in used if u in vals): o.write(rust(n, vals[n]) + "\n")
with open(os.path.join(SRC, "names.rs"), "w") as o:
    o.write("//! GENERATED by tools/gen-mui-ids.py from MUI's libraries/mui.h and Zune's class headers: every attribute (MUIA_) and method\n//! (MUIM_) id with its name, sorted by id. Attributes and methods share one id space in Zune's private range, so they are two tables.\n")
    seen = {}
    for table, pre in (("ATTR_NAMES", "MUIA_"), ("METHOD_NAMES", "MUIM_")):
        o.write(f"pub const {table}: &[(u32, &str)] = &[\n")
        done = set()
        for n, v in sorted(vals.items(), key=lambda kv: (kv[1], kv[0])):
            if n.startswith(pre) and v >= 0x80000000 and v not in done:
                done.add(v); o.write(f'    ({v:#010x}, "{n}"),\n')
        o.write("];\n")
        seen[table] = done
print(len(used), "names used,", {k: len(v) for k, v in seen.items()}, "ids named")
